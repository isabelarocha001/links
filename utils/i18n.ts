/**
 * i18n — textos da página de links (cards, quiz gate, bio, CTAs).
 *
 * detectLocale(): idioma do navegador (pt/en/es/fr/de/it)
 * isBrazilAudience(): true só para pt-BR (Portugal = internacional)
 * t(locale, key): busca tradução; fallback pt → key
 *
 * Chaves importantes dos cards:
 *   vipTitle / vipDesc  → card bot/Telegram VIP (BR)
 *   pubTitle / pubDesc  → canal público
 *   privTitle / privDesc → PrivSex
 */
export type Locale = 'pt' | 'en' | 'es' | 'fr' | 'de' | 'it' | 'nl' | 'sv' | 'no' | 'da' | 'fi' | 'pl' | 'cs' | 'el' | 'ro' | 'hu'

export function detectLocale(languagePreferences?: readonly string[]): Locale {
  const list = languagePreferences?.length
    ? [...languagePreferences]
    : typeof navigator === 'undefined'
      ? ['pt']
      : [...(navigator.languages || []), navigator.language || 'pt']
  for (const raw of list) {
    const code = String(raw || '').toLowerCase().slice(0, 2)
    if (code === 'pt') return 'pt'
    if (code === 'en') return 'en'
    if (code === 'es') return 'es'
    if (code === 'fr') return 'fr'
    if (code === 'de') return 'de'
    if (code === 'it') return 'it'
    if (code === 'nl') return 'nl'
    if (code === 'sv') return 'sv'
    if (code === 'no' || code === 'nb' || code === 'nn') return 'no'
    if (code === 'da') return 'da'
    if (code === 'fi') return 'fi'
    if (code === 'pl') return 'pl'
    if (code === 'cs') return 'cs'
    if (code === 'el') return 'el'
    if (code === 'ro') return 'ro'
    if (code === 'hu') return 'hu'
  }
  return 'pt'
}

/** BR market only: pt-BR (or bare "pt"). Portugal (pt-PT) is international. */
/**
 * Brasil = idioma PRINCIPAL do navegador é pt-BR (ou pt sem região).
 * Não usa navigator.languages inteira: se o lead tem en-US como principal
 * e pt-BR só na lista, deve ser tratado como gringo (Stripe), não PIX.
 */
export function isBrazilAudience(): boolean {
  if (typeof navigator === 'undefined') return true
  const primary = String(navigator.language || 'pt-BR').toLowerCase().replace(/_/g, '-')
  if (primary === 'pt-pt' || primary.startsWith('pt-pt-')) return false
  if (primary === 'pt-br' || primary.startsWith('pt-br-')) return true
  if (primary === 'pt' || primary === 'pt-') return true
  // só "pt" genérico sem região
  if (primary.startsWith('pt-') && !primary.startsWith('pt-pt')) {
    // pt-AO etc. → tratar como BR/PIX por padrão
    return true
  }
  return false
}

